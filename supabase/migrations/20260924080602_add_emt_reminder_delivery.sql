alter table public.emt_settings
  add column if not exists meeting_anchor_date date not null default '2026-09-14';

create table if not exists public.emt_reminder_deliveries (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  workspace_id text not null default 'gms-emt',
  topic_id bigint not null references public.emt_topics(id) on delete cascade,
  reminder_type text not null,
  recipient_name text not null,
  recipient_email text not null,
  subject text not null,
  scheduled_for date not null,
  status text not null default 'prepared',
  attempt_count smallint not null default 0,
  graph_request_id text,
  error_message text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint emt_reminder_delivery_type_check check (
    reminder_type in ('agenda_preparation', 'follow_up_due', 'follow_up_overdue')
  ),
  constraint emt_reminder_delivery_status_check check (
    status in ('prepared', 'sent', 'failed', 'skipped')
  ),
  constraint emt_reminder_delivery_recipient_check check (
    lower(recipient_email) in (
      'lisa.xu@gms.global',
      'george@gms.global',
      'brenda@gms.global',
      'coco.hu@gms.global'
    )
  )
);

create index if not exists emt_reminder_deliveries_schedule_idx
  on public.emt_reminder_deliveries (scheduled_for desc, status);

