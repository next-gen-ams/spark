create table public.emt_members (
  display_name text primary key,
  email text unique,
  microsoft_object_id text unique,
  active boolean not null default true,
  first_connected_at timestamptz,
  last_connected_at timestamptz,
  created_at timestamptz not null default now(),
  constraint emt_members_display_name_length check (char_length(display_name) between 2 and 120),
  constraint emt_members_email_domain check (email is null or lower(email) like '%@gms.global')
);

create table public.emt_topics (
  id bigint generated by default as identity primary key,
  bucket text not null default 'agenda',
  title text not null,
  category text not null,
  status text not null default 'Scheduled',
  lead text not null,
  lead_initials text not null,
  time_minutes smallint not null default 10,
  note text not null default '',
  reminder text not null default 'Not scheduled',
  prep_action text not null default '',
  decision text not null default '',
  follow_up_owner text not null default '',
  follow_up_action text not null default '',
  due_date date,
  decision_date date,
  source text not null default 'Agenda',
  remind_lead boolean not null default false,
  remind_followup boolean not null default false,
  created_by text,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint emt_topics_bucket_check check (bucket in ('agenda', 'backlog', 'history')),
  constraint emt_topics_category_check check (category in ('People & culture', 'Operations', 'Governance', 'Finance')),
  constraint emt_topics_status_check check (status in ('Scheduled', 'Needs lead', 'Needs input')),
  constraint emt_topics_title_length check (char_length(title) between 1 and 160),
  constraint emt_topics_time_check check (time_minutes between 1 and 180)
);

create index emt_topics_bucket_idx on public.emt_topics (bucket, id);
create index emt_topics_decision_date_idx on public.emt_topics (decision_date desc) where decision <> '';

create table public.emt_settings (
  workspace_id text primary key default 'gms-emt',
  reminders_on boolean not null default true,
  agenda_reminder_timing text not null default '2 business days before',
  followup_reminder_timing text not null default '1 business day before',
  overdue_reminders_on boolean not null default true,
  business_days_only boolean not null default true,
  updated_by text,
  updated_at timestamptz not null default now()
);

alter table public.emt_members enable row level security;
alter table public.emt_topics enable row level security;
alter table public.emt_settings enable row level security;

revoke all on table public.emt_members from anon, authenticated;
revoke all on table public.emt_topics from anon, authenticated;
revoke all on table public.emt_settings from anon, authenticated;
grant select, insert, update, delete on table public.emt_members to service_role;
grant select, insert, update, delete on table public.emt_topics to service_role;
grant select, insert, update, delete on table public.emt_settings to service_role;
grant usage, select on sequence public.emt_topics_id_seq to service_role;

