create table public.emt_topic_categories (
  id bigint generated by default as identity primary key,
  name text not null,
  sort_order integer not null default 0,
  active boolean not null default true,
  system boolean not null default false,
  created_by text,
  updated_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint emt_topic_categories_name_length check (char_length(trim(name)) between 1 and 40)
);

create unique index emt_topic_categories_name_unique
  on public.emt_topic_categories (lower(name));
create index emt_topic_categories_active_order_idx
  on public.emt_topic_categories (active, sort_order, id);

alter table public.emt_topic_categories enable row level security;
revoke all on table public.emt_topic_categories from anon, authenticated;
grant select, insert, update, delete on table public.emt_topic_categories to service_role;
grant usage, select on sequence public.emt_topic_categories_id_seq to service_role;

