create or replace function public.emt_rename_category(
  p_id bigint,
  p_name text,
  p_updated_by text
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  target public.emt_topic_categories%rowtype;
  renamed public.emt_topic_categories%rowtype;
  clean_name text := trim(p_name);
begin
  select * into target
  from public.emt_topic_categories
  where id = p_id and active = true
  for update;

  if not found then
    raise exception 'Topic was not found.';
  end if;
  if target.system then
    raise exception 'System topics cannot be renamed.';
  end if;
  if char_length(clean_name) < 1 or char_length(clean_name) > 40 then
    raise exception 'Topic name must be between 1 and 40 characters.';
  end if;
  if exists (
    select 1 from public.emt_topic_categories
    where lower(name) = lower(clean_name) and id <> p_id
  ) then
    raise exception 'A topic with this name already exists.';
  end if;

  update public.emt_topics
  set category = clean_name,
      updated_by = p_updated_by,
      updated_at = now()
  where category = target.name;

  update public.emt_topic_categories
  set name = clean_name,
      updated_by = p_updated_by,
      updated_at = now()
  where id = p_id
  returning * into renamed;

  return jsonb_build_object(
    'id', renamed.id,
    'name', renamed.name,
    'sort_order', renamed.sort_order,
    'active', renamed.active,
    'system', renamed.system,
    'usage_count', (select count(*) from public.emt_topics where category = renamed.name)
  );
end;
$$;

create or replace function public.emt_delete_category(
  p_id bigint,
  p_updated_by text
)
returns jsonb
language plpgsql
security invoker
set search_path = public
as $$
declare
  target public.emt_topic_categories%rowtype;
  reassigned_count integer;
begin
  select * into target
  from public.emt_topic_categories
  where id = p_id and active = true
  for update;

  if not found then
    raise exception 'Topic was not found.';
  end if;
  if target.system then
    raise exception 'System topics cannot be deleted.';
  end if;

  update public.emt_topics
  set category = 'Uncategorised',
      updated_by = p_updated_by,
      updated_at = now()
  where category = target.name;
  get diagnostics reassigned_count = row_count;

  update public.emt_topic_categories
  set active = false,
      updated_by = p_updated_by,
      updated_at = now()
  where id = p_id;

  return jsonb_build_object(
    'deletedCategory', target.name,
    'reassignedCount', reassigned_count
  );
end;
$$;

revoke all on function public.emt_rename_category(bigint, text, text) from public, anon, authenticated;
revoke all on function public.emt_delete_category(bigint, text) from public, anon, authenticated;
grant execute on function public.emt_rename_category(bigint, text, text) to service_role;
grant execute on function public.emt_delete_category(bigint, text) to service_role;
