create table if not exists public.emt_member_mail_deliveries (
  id bigint generated by default as identity primary key,
  request_id uuid not null unique,
  sender_email text not null references public.emt_members(email) on update cascade,
  recipient_emails text[] not null,
  topic_id bigint not null references public.emt_topics(id) on delete cascade,
  subject text not null,
  status text not null default 'pending',
  graph_request_id text,
  error_message text,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  constraint emt_member_mail_recipient_count check (
    cardinality(recipient_emails) between 1 and 3
  ),
  constraint emt_member_mail_status check (
    status in ('pending', 'sent', 'failed')
  )
);

create index if not exists emt_member_mail_sender_created_idx
  on public.emt_member_mail_deliveries (sender_email, created_at desc);

alter table public.emt_member_mail_deliveries enable row level security;
revoke all on table public.emt_member_mail_deliveries from anon, authenticated;
grant select, insert, update on table public.emt_member_mail_deliveries to service_role;
grant usage, select on sequence public.emt_member_mail_deliveries_id_seq to service_role;

comment on table public.emt_member_mail_deliveries is
  'Audit trail for member-initiated EMT emails sent with delegated Microsoft Mail.Send permission. Access tokens are never stored.';
